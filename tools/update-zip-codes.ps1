param([string]$Archive)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
if (-not $Archive) {
    $Archive = Join-Path $root 'build/US.zip'
    New-Item -ItemType Directory -Force (Split-Path $Archive) | Out-Null
    Invoke-WebRequest 'https://download.geonames.org/export/zip/US.zip' -OutFile $Archive
}
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead($Archive)
try {
    $reader = [IO.StreamReader]::new($zip.GetEntry('US.txt').Open())
    $records = @{}
    try {
        while (($line = $reader.ReadLine()) -ne $null) {
            $fields = $line.Split("`t")
            if ($fields[1] -notmatch '^\d{5}$') { continue }
            $code = [int]$fields[1]
            $lat = [double]::Parse($fields[9], [Globalization.CultureInfo]::InvariantCulture)
            $lon = [double]::Parse($fields[10], [Globalization.CultureInfo]::InvariantCulture)
            if ([Math]::Abs($lat) -gt 90 -or [Math]::Abs($lon) -gt 180) { throw 'Invalid coordinate in ZIP dataset' }
            # Match the API's first-place convention for duplicate postal codes.
            if (-not $records.ContainsKey($code)) { $records[$code] = @([int][Math]::Round($lat * 100000), [int][Math]::Round($lon * 100000)) }
        }
    } finally { $reader.Dispose() }
} finally { $zip.Dispose() }
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/update-zip-codes.ps1 from GeoNames US postal data.')
[void]$output.AppendLine('// https://www.geonames.org/ | CC BY 4.0; coordinates rounded to 1e-5 degrees.')
[void]$output.AppendLine('// Archive SHA256: ' + (Get-FileHash $Archive -Algorithm SHA256).Hash)
foreach ($code in ($records.Keys | Sort-Object)) {
    $point = $records[$code]
    [void]$output.AppendLine('{' + $code + ',' + $point[0] + ',' + $point[1] + '},')
}
[IO.File]::WriteAllText((Join-Path $root 'src/ZipCodeData.h'), $output.ToString(), [Text.UTF8Encoding]::new($false))
Write-Output ('Generated ' + $records.Count + ' US ZIP records (' + ($records.Count * 12) + ' bytes in flash).')
